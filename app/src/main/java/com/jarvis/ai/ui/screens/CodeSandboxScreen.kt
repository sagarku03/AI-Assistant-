import com.jarvis.ai.ui.theme.TextSecondary

@SuppressLint("SetJavaScriptEnabled")
@Composable
fun CodeSandboxScreen(
    onNavigateBack: () -> Unit
) {
    var selectedTab by remember { mutableStateOf(0) } // 0: Live Preview, 1: Source Code

    // Sample modern neon website generated by JARVIS on mobile
    var sampleGeneratedHtml by remember {
        mutableStateOf(
            """
            <!DOCTYPE html>
            <html lang="en">
            <head>
                <meta name="viewport" content="width=device-width, initial-scale=1.0">
                <style>
                    body {
                        margin: 0;
                        padding: 24px;
                        background: #08090C;
                        color: #FFFFFF;
                        font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
                        display: flex;
                        flex-direction: column;
                        align-items: center;
                        justify-content: center;
                        min-height: 80vh;
                        box-sizing: border-box;
                    }
                    .glass-card {
                        background: rgba(255, 255, 255, 0.05);
                        border: 1px solid rgba(255, 255, 255, 0.15);
                        border-radius: 24px;
                        padding: 32px;
                        text-align: center;
                        box-shadow: 0 8px 32px 0 rgba(0, 242, 254, 0.15);
                        max-width: 320px;
                        width: 100%;
                    }
                    h1 {
                        font-size: 24px;
                        margin-bottom: 8px;
                        background: linear-gradient(135deg, #00F2FE 0%, #4FACFE 100%);
                        -webkit-background-clip: text;
                        -webkit-text-fill-color: transparent;
                    }
                    p {
                        color: #A1A1AA;
                        font-size: 14px;
                        line-height: 1.5;
                    }
                    .btn {
                        margin-top: 20px;
                        padding: 12px 28px;
                        border-radius: 20px;
                        border: none;
                        background: #00E676;
                        color: #000;
                        font-weight: bold;
                        cursor: pointer;
                    }
                </style>
            </head>
            <body>
                <div class="glass-card">
                    <h1>JARVIS Studio</h1>
                    <p>This interactive website was autonomously coded & deployed directly on your mobile device by JARVIS.</p>
                    <button class="btn" onclick="alert('Hello from JARVIS!')">Test Interaction</button>
                </div>
            </body>
            </html>
            """.trimIndent()
        )
    }

    Column(
        modifier = Modifier
            .fillMaxSize()
            .background(OledBlack)
            .padding(horizontal = 20.dp, vertical = 24.dp)
    ) {
        // Top Bar
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .padding(top = 16.dp),
            verticalAlignment = Alignment.CenterVertically
        ) {
            IconButton(
                onClick = onNavigateBack,
                modifier = Modifier
                    .size(40.dp)
                    .glassmorphic(shape = RoundedCornerShape(12.dp))
            ) {
                Icon(
                    imageVector = Icons.AutoMirrored.Rounded.ArrowBack,
                    contentDescription = "Back",
                    tint = TextPrimary
                )
            }

            Spacer(modifier = Modifier.width(16.dp))

            Column {
                Text(
                    text = "Mobile Code Studio",
                    fontSize = 20.sp,
                    fontWeight = FontWeight.Bold,
                    color = TextPrimary
                )
                Text(
                    text = "Live website generation & preview",
                    fontSize = 12.sp,
                    color = TextSecondary
                )
            }
        }

        Spacer(modifier = Modifier.height(20.dp))

        // Tab Selector (Live Preview vs Code)
        Row(
            modifier = Modifier
                .fillMaxWidth()
                .glassmorphic(shape = RoundedCornerShape(18.dp))
                .padding(4.dp),
            horizontalArrangement = Arrangement.SpaceBetween
        ) {
            PillButton(
                text = "Live Preview",
                modifier = Modifier.weight(1f),
                style = if (selectedTab == 0) PillButtonStyle.GRADIENT_CYAN else PillButtonStyle.GLASS_TRANSLUCENT,
                onClick = { selectedTab = 0 }
            )
            Spacer(modifier = Modifier.width(8.dp))
            PillButton(
                text = "Source Code",
                modifier = Modifier.weight(1f),
                style = if (selectedTab == 1) PillButtonStyle.GRADIENT_CYAN else PillButtonStyle.GLASS_TRANSLUCENT,
                onClick = { selectedTab = 1 }
            )
        }

        Spacer(modifier = Modifier.height(16.dp))

        // Display Area
        Box(
            modifier = Modifier
                .fillMaxWidth()
                .weight(1f)
                .glassmorphic(shape = RoundedCornerShape(24.dp))
                .clip(RoundedCornerShape(24.dp))
        ) {
            if (selectedTab == 0) {
                // Interactive Embedded WebView Live Preview
                AndroidView(
                    modifier = Modifier.fillMaxSize(),
                    factory = { context ->
                        WebView(context).apply {
                            layoutParams = ViewGroup.LayoutParams(
                                ViewGroup.LayoutParams.MATCH_PARENT,
                                ViewGroup.LayoutParams.MATCH_PARENT
                            )
                            settings.javaScriptEnabled = true
                            settings.domStorageEnabled = true
                            setBackgroundColor(0xFF08090C.toInt())
                            webViewClient = WebViewClient()
                            loadDataWithBaseURL(null, sampleGeneratedHtml, "text/html", "UTF-8", null)
                        }
                    },
                    update = { webView ->
                        webView.loadDataWithBaseURL(null, sampleGeneratedHtml, "text/html", "UTF-8", null)
                    }
                )
            } else {
                // Source Code View
                Column(
                    modifier = Modifier
                        .fillMaxSize()
                        .padding(16.dp)
                        .verticalScroll(rememberScrollState())
                ) {
                    Text(
                        text = sampleGeneratedHtml,
                        fontFamily = FontFamily.Monospace,
                        fontSize = 12.sp,
                        color = JarvisCyan
                    )
                }
            }
        }

        Spacer(modifier = Modifier.height(16.dp))

        // Quick Generator Action
        GlassCard(
            modifier = Modifier.fillMaxWidth(),
            contentPadding = 14.dp
        ) {
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Text(
                    text = "Saved to: /sdcard/JarvisProjects/",
                    fontSize = 12.sp,
                    color = TextSecondary
                )
                PillButton(
                    text = "Export",
                    style = PillButtonStyle.NEON_LIME,
                    padding = androidx.compose.foundation.layout.PaddingValues(horizontal = 16.dp, vertical = 8.dp),
                    onClick = {}
                )
            }
        }
    }
}
